def _source_json(source: SourceInfo, *, include_supporting: bool) -> dict[str, Any]:
    data: dict[str, Any] = {
        "index": source.index,
        "chunk_id": str(source.chunk_id),
        "document_id": str(source.document_id),
        "filename": source.filename,
        "chunk_ordinal": source.chunk_ordinal,
        "page_start": source.page_start,
        "page_end": source.page_end,
        "section": source.section,
        "language": source.language,
        "retrieval_rank": source.retrieval_rank,
        "score": source.score,
        "score_type": source.score_type,
        "excerpt": source.excerpt,
    }
    if include_supporting:
        data["supporting"] = source.supporting
    return data


def _usage_json(usage: Usage) -> dict[str, int]:
    return {
        "input_tokens": usage.input_tokens,
        "output_tokens": usage.output_tokens,
        "cache_read_input_tokens": usage.cache_read_input_tokens,
        "cache_creation_input_tokens": usage.cache_creation_input_tokens,
    }


def event_payload(event: ChatEvent, request_id: str | None) -> tuple[str, dict[str, Any]]:
    """The SSE event name and JSON data for a pipeline event."""
    match event:
        case Started():
            return "start", {
                "request_id": request_id,
                "conversation_id": str(event.conversation_id),
                "user_message_id": str(event.user_message_id),
                "assistant_message_id": str(event.assistant_message_id),
                "provider": event.provider,
                "model": event.model,
                "replayed": event.replayed,
            }
        case SourcesFound():
            return "sources", {
                "retrieval": {
                    "mode": event.mode,
                    "semantic_available": event.semantic_available,
                    "warnings": event.warnings,
                    "duration_ms": event.retrieval_ms,
                },
                "sources": [_source_json(s, include_supporting=False) for s in event.sources],
            }
        case Delta():
            return "delta", {"text": event.text}
        case CitationsChecked():
            return "citations", {
                "citations": [_source_json(s, include_supporting=True) for s in event.citations],
                "invalid_markers_removed": event.invalid_markers_removed,
            }
        case UsageReported():
            return "usage", _usage_json(event.usage)
        case Finished():
            return "done", {
                "assistant_message_id": str(event.assistant_message_id),
                "status": event.status,
                "grounding": event.grounding,
                "stop_reason": event.stop_reason,
                "served_model": event.served_model,
                "timings_ms": event.timings_ms,
            }
        case Failed():
            return "error", {
                "code": event.code,
                "message": event.message,
                "retryable": event.retryable,
                "retry_after_seconds": event.retry_after_seconds,
                "assistant_message_id": (
                    str(event.assistant_message_id) if event.assistant_message_id else None
                ),
                "request_id": request_id,
            }
    raise TypeError(f"unknown chat event {type(event).__name__}")  # pragma: no cover


def format_sse(event_id: int, name: str, data: dict[str, Any]) -> bytes:
    # json.dumps never emits a raw newline, so the data always fits on one "data:" line.
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    return f"id: {event_id}\nevent: {name}\ndata: {payload}\n\n".encode()


_STREAM_END = object()


async def _sse_stream(
    events: AsyncIterator[ChatEvent],
    request_id: str | None,
    heartbeat_seconds: float,
    tasks: set[asyncio.Task[None]],
) -> AsyncIterator[bytes]:
    """Run the pipeline in its own task and relay its events, with keep-alive comments.

    If the client goes away, Starlette cancels this generator; the pipeline task is then
    cancelled once and stores the partial answer as ``cancelled`` on its own (it is not
    awaited here, because this generator's cancellation would interrupt that write).
    """
    queue: asyncio.Queue[object] = asyncio.Queue()

    async def produce() -> None:
        try:
            async for event in events:
                queue.put_nowait(event)
        except asyncio.CancelledError:
            raise
        except Exception:
            logger.exception("chat_stream_failed")
            queue.put_nowait(
                Failed("internal_error", "The answer could not be completed.", retryable=True)
            )
        finally:
            queue.put_nowait(_STREAM_END)

    producer = asyncio.create_task(produce(), name="chat-answer")
    tasks.add(producer)
    producer.add_done_callback(tasks.discard)
    event_id = 0
    try:
        yield b": stream open\n\n"
        while True:
            try:
                item = await asyncio.wait_for(queue.get(), heartbeat_seconds)
            except TimeoutError:
                yield b": keep-alive\n\n"
                continue
            if item is _STREAM_END:
                break
            event_id += 1
            name, data = event_payload(item, request_id)  # type: ignore[arg-type]
            yield format_sse(event_id, name, data)
    finally:
        if not producer.done():
            producer.cancel()


async def _replay_events(
    session: Any, conversation_id: uuid.UUID, replay: Replay
) -> list[ChatEvent]:
    answer = await session.get(Message, replay.assistant_message_id)
    citations = (
        await session.scalars(
            select(MessageCitation)
            .where(MessageCitation.message_id == answer.id)
            .order_by(MessageCitation.source_index)
        )
    ).all()
    sources = [
        SourceInfo(
            index=c.source_index,
            chunk_id=c.chunk_id,
            document_id=c.document_id,
            filename=c.filename,
            chunk_ordinal=c.chunk_ordinal,
            page_start=c.page_start,
            page_end=c.page_end,
            section=c.section,
            language=c.language,
            retrieval_rank=c.retrieval_rank,
            score=c.score,
            score_type=c.score_type,
            excerpt=c.excerpt,
            supporting=c.supporting,
        )
        for c in citations
    ]
    events: list[ChatEvent] = [
        Started(
            conversation_id,
            replay.user_message_id,
            answer.id,
            answer.provider,
            answer.model,
            replayed=True,
        ),
        SourcesFound(
            answer.retrieval_mode or "", "", True, [], answer.retrieval_ms or 0.0, sources
        ),
        Delta(answer.content),
        CitationsChecked(sources, 0),
    ]
    usage = _usage(answer)
    if usage is not None:
        events.append(UsageReported(Usage(**usage.model_dump())))
    events.append(
        Finished(
            answer.id,
            answer.status,
            answer.grounding,
            answer.stop_reason,
            answer.served_model,
            {"total_ms": answer.total_ms} if answer.total_ms is not None else {},
        )
    )
    return events


async def _iterate(events: list[ChatEvent]) -> AsyncIterator[ChatEvent]:
    for event in events:
        yield event


_SSE_HEADERS = {"Cache-Control": "no-cache", "X-Accel-Buffering": "no"}


@router.post(
    "/conversations/{conversation_id}/messages",
    response_class=StreamingResponse,
    responses={
        200: {
            "content": {"text/event-stream": {}},
            "description": "Server-Sent Events: start, sources, delta, citations, usage, done "
            "or error (see docs/chat-api.md).",
        },
        404: {"model": ErrorResponse, "description": "Conversation not found"},
        409: {"model": ErrorResponse, "description": "An answer is already being generated"},
        422: {"model": ErrorResponse, "description": "Invalid question or filters"},
        429: {"model": ErrorResponse, "description": "Too many answers in progress"},
        503: {"model": ErrorResponse, "description": "LLM not configured or database down"},
    },
)
async def ask(
    conversation_id: uuid.UUID, body: AskBody, request: Request, session: Session, chat: Chat
) -> StreamingResponse:
    """Ask a question and stream a grounded answer with citations.

    Errors found before the answer starts (unknown conversation, invalid input, missing
    configuration, a busy conversation) are ordinary JSON error responses. Once the stream
    has started, failures arrive as an ``error`` event and the stream ends.
    """
    settings = request.app.state.settings
    if len(body.content) > settings.chat_max_question_chars:
        raise ApiError(
            422,
            "question_too_long",
            f"The question must be at most {settings.chat_max_question_chars} characters.",
        )
    retrieval = body.retrieval or RetrievalBody()
    ask_request = AskRequest(
        conversation_id=conversation_id,
        question=body.content,
        client_message_id=body.client_message_id,
        retrieval=RetrievalOptions(
            mode=retrieval.mode,
            document_ids=tuple(retrieval.document_ids) if retrieval.document_ids else None,
            language=retrieval.language,
        ),
        request_id=request_id_var.get(),
    )
    try:
        if retrieval.document_ids:
            missing = await unknown_document_ids(session, retrieval.document_ids)
            if missing:
                raise ApiError(
                    422,
                    "unknown_document",
                    f"Unknown document ID(s): {', '.join(str(i) for i in missing[:5])}.",
                )
        replay = await chat.check(session, ask_request)
        replay_events = await _replay_events(session, conversation_id, replay) if replay else None
        await session.rollback()
    except ChatError as exc:
        headers = {"Retry-After": str(int(exc.retry_after))} if exc.retry_after else None
        raise ApiError(exc.status_code, exc.code, exc.message, headers=headers) from exc
    except SQLAlchemyError as exc:
        raise _database_error(exc) from exc

    if replay_events is not None:
        logger.info("chat_answer_replayed", extra={"conversation_id": str(conversation_id)})
        events: AsyncIterator[ChatEvent] = _iterate(replay_events)
    else:
        events = chat.answer(ask_request)
    return StreamingResponse(
        _sse_stream(
            events,
            ask_request.request_id,
            settings.chat_heartbeat_seconds,
            request.app.state.chat_tasks,
        ),
        media_type="text/event-stream",
        headers=_SSE_HEADERS,
    )


