def _usage(message: Message) -> UsageOut | None:
    if message.input_tokens is None and message.output_tokens is None:
        return None
    return UsageOut(
        input_tokens=message.input_tokens or 0,
        output_tokens=message.output_tokens or 0,
        cache_read_input_tokens=message.cache_read_input_tokens or 0,
        cache_creation_input_tokens=message.cache_creation_input_tokens or 0,
    )


def _citation_out(citation: MessageCitation, location: SourceLocation) -> CitationOut:
    return CitationOut(
        index=citation.source_index,
        supporting=citation.supporting,
        chunk_id=citation.chunk_id,
        document_id=citation.document_id,
        filename=citation.filename,
        chunk_ordinal=citation.chunk_ordinal,
        page_start=citation.page_start,
        page_end=citation.page_end,
        section=citation.section,
        language=citation.language,
        retrieval_rank=citation.retrieval_rank,
        score=citation.score,
        score_type=citation.score_type,
        excerpt=citation.excerpt,
        source_status=location.status,
        current_chunk_id=location.chunk_id,
        current_chunk_ordinal=location.chunk_ordinal,
    )


def _message_out(
    message: Message, citations: list[MessageCitation], locations: dict[uuid.UUID, SourceLocation]
) -> MessageOut:
    timings = {
        key: value
        for key, value in (
            ("retrieval_ms", message.retrieval_ms),
            ("first_token_ms", message.first_token_ms),
            ("total_ms", message.total_ms),
        )
        if value is not None
    }
    return MessageOut(
        id=message.id,
        sequence=message.sequence,
        role=message.role,  # type: ignore[arg-type]
        content=message.content,
        status=MessageStatus(message.status),
        created_at=message.created_at,
        completed_at=message.completed_at,
        client_message_id=message.client_message_id,
        reply_to_id=message.reply_to_id,
        grounding=message.grounding,
        error_code=message.error_code,
        error_message=message.error_message,
        provider=message.provider,
        model=message.model,
        served_model=message.served_model,
        stop_reason=message.stop_reason,
        usage=_usage(message),
        retrieval_mode=message.retrieval_mode,
        timings_ms=timings,
        citations=[_citation_out(c, locations[c.id]) for c in citations],
    )


async def _conversation_or_404(session: Any, conversation_id: uuid.UUID) -> Conversation:
    conversation = await session.get(Conversation, conversation_id)
    if conversation is None:
        raise ApiError(404, "conversation_not_found", "Conversation not found.")
    return conversation


async def _detail(session: Any, conversation: Conversation) -> ConversationDetail:
    messages, citations = await load_messages(session, conversation.id, MESSAGE_LIMIT + 1)
    truncated = len(messages) > MESSAGE_LIMIT
    if truncated:
        messages = messages[1:]
    all_citations = [c for m in messages for c in citations[m.id]]
    locations = await locate_sources(session, all_citations)
    return ConversationDetail(
        id=conversation.id,
        title=conversation.title,
        created_at=conversation.created_at,
        updated_at=conversation.updated_at,
        message_count=len(messages),
        messages=[_message_out(m, citations[m.id], locations) for m in messages],
        messages_truncated=truncated,
    )


def _database_error(exc: SQLAlchemyError) -> ApiError:
    logger.warning("chat_database_error", extra={"error_type": type(exc).__name__})
    return ApiError(503, "database_unavailable", "The database is unavailable.")


