@router.post("/conversations", status_code=201, response_model=ConversationSummary)
async def create_conversation(body: ConversationCreate, session: Session) -> ConversationSummary:
    """Start a conversation. Without a title, the first question becomes the title."""
    conversation = Conversation(
        id=uuid.uuid4(), title=body.title or DEFAULT_TITLE, title_is_default=body.title is None
    )
    try:
        session.add(conversation)
        await session.commit()
        await session.refresh(conversation)
    except SQLAlchemyError as exc:
        raise _database_error(exc) from exc
    logger.info("conversation_created", extra={"conversation_id": str(conversation.id)})
    return ConversationSummary(
        id=conversation.id,
        title=conversation.title,
        created_at=conversation.created_at,
        updated_at=conversation.updated_at,
        message_count=0,
    )


@router.get("/conversations", response_model=ConversationList)
async def get_conversations(
    session: Session,
    limit: Annotated[int, Query(ge=1, le=100)] = 50,
    offset: Annotated[int, Query(ge=0)] = 0,
) -> ConversationList:
    """Conversations, most recently active first."""
    rows, total = await list_conversations(session, limit, offset)
    return ConversationList(
        items=[
            ConversationSummary(
                id=c.id,
                title=c.title,
                created_at=c.created_at,
                updated_at=c.updated_at,
                message_count=count,
            )
            for c, count in rows
        ],
        total=total,
        limit=limit,
        offset=offset,
    )


@router.get(
    "/conversations/{conversation_id}", response_model=ConversationDetail, responses=_NOT_FOUND
)
async def get_conversation(conversation_id: uuid.UUID, session: Session) -> ConversationDetail:
    """A conversation with its messages (oldest first) and each answer's citations.

    Each citation reports whether its passage still exists (``source_status``), so a client
    can link to the passage even after the document was reindexed.
    """
    conversation = await _conversation_or_404(session, conversation_id)
    return await _detail(session, conversation)


@router.patch(
    "/conversations/{conversation_id}", response_model=ConversationSummary, responses=_NOT_FOUND
)
async def rename_conversation(
    conversation_id: uuid.UUID, body: ConversationRename, session: Session
) -> ConversationSummary:
    conversation = await session.get(Conversation, conversation_id, with_for_update=True)
    if conversation is None:
        raise ApiError(404, "conversation_not_found", "Conversation not found.")
    conversation.title = body.title
    conversation.title_is_default = False
    await session.commit()
    await session.refresh(conversation)
    count = await session.scalar(
        select(func.count()).select_from(Message).where(Message.conversation_id == conversation.id)
    )
    return ConversationSummary(
        id=conversation.id,
        title=conversation.title,
        created_at=conversation.created_at,
        updated_at=conversation.updated_at,
        message_count=count or 0,
    )


@router.delete("/conversations/{conversation_id}", status_code=204, responses=_NOT_FOUND)
async def delete_conversation(conversation_id: uuid.UUID, session: Session) -> Response:
    """Delete the conversation, its messages and their citations.

    An answer still being generated is stopped from being stored; its stream ends normally.
    """
    conversation = await session.get(Conversation, conversation_id, with_for_update=True)
    if conversation is None:
        raise ApiError(404, "conversation_not_found", "Conversation not found.")
    await session.delete(conversation)
    await session.commit()
    logger.info("conversation_deleted", extra={"conversation_id": str(conversation_id)})
    return Response(status_code=204)


