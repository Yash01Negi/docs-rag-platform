class ConversationCreate(BaseModel):
    model_config = ConfigDict(extra="forbid")

    title: str | None = Field(default=None, max_length=200)

    @field_validator("title")
    @classmethod
    def _title(cls, value: str | None) -> str | None:
        return None if value is None else _clean_text(value, "title")


class ConversationRename(BaseModel):
    model_config = ConfigDict(extra="forbid")

    title: str = Field(min_length=1, max_length=200)

    @field_validator("title")
    @classmethod
    def _title(cls, value: str) -> str:
        return " ".join(_clean_text(value, "title").split())


class RetrievalBody(BaseModel):
    model_config = ConfigDict(extra="forbid")

    mode: SearchMode | None = Field(
        default=None, description="Retrieval mode. Defaults to CHAT_RETRIEVAL_MODE."
    )
    document_ids: list[uuid.UUID] | None = Field(default=None, min_length=1, max_length=100)
    language: Literal["ja", "en", "mixed"] | None = None

    @field_validator("document_ids")
    @classmethod
    def _unique(cls, value: list[uuid.UUID] | None) -> list[uuid.UUID] | None:
        if value is not None and len(set(value)) != len(value):
            raise ValueError("document_ids must not contain duplicates")
        return value


class AskBody(BaseModel):
    model_config = ConfigDict(extra="forbid")

    content: str = Field(min_length=1, description="The question, in Japanese or English.")
    client_message_id: uuid.UUID | None = Field(
        default=None,
        description=(
            "Idempotency key generated by the client. Sending the same question again with "
            "the same key never stores it twice: a completed answer is replayed, a failed or "
            "stopped one is generated again."
        ),
    )
    retrieval: RetrievalBody | None = None

    @field_validator("content")
    @classmethod
    def _content(cls, value: str) -> str:
        return _clean_text(value, "content")


